// Extracts the four compass characters (北 東 南 西) from a font as SVG path
// data and writes src/scripts/three/instrument/glyphs.ts, which is committed.
// The site ships no webfont for them: the dial draws these outlines only.
//
//   node tools/glyphs.mjs <font.ttf>
//
// The font is Noto Serif TC Bold (SIL Open Font License), subset to these four
// characters. Each outline is scaled so 1 em = 1 unit and moved so its bounding
// box is centred on (0.5, 0.5) of a 1 x 1 em box, y down, which lets the
// drawing and the 3D face place a glyph by its centre. The credit line comes
// from the font's own name records, so the licence text can never drift from
// the file the outlines came from. Any gap (a missing glyph, copyright or
// licence URL) stops the run with an error rather than writing a partial file.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const CHARS = ['北', '東', '南', '西'];
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src', 'scripts', 'three', 'instrument', 'glyphs.ts');

function fail(message) {
  console.error(`[glyphs] ${message}`);
  process.exit(1);
}

const source = process.argv[2];
if (!source) fail('usage: node tools/glyphs.mjs <font.ttf>');

const bytes = await readFile(source);
const font = opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
const em = font.unitsPerEm;
if (!(em > 0)) fail('the font has no unitsPerEm');

/** An English name record from the font's Windows table, or a loud failure. */
function record(key) {
  const value = font.names?.windows?.[key]?.en;
  if (typeof value !== 'string' || value.trim() === '') fail(`the font has no ${key} record`);
  return value.trim();
}

const credit = `${record('fullName')}. ${record('copyright')} Licensed under the SIL Open Font License, ${record('licenseURL')}.`;

/** A coordinate pair of a path command, moved to `(dx, dy)` and scaled by 1/em. */
function place(command, dx, dy) {
  const moved = { ...command };
  for (const [x, y] of [['x', 'y'], ['x1', 'y1'], ['x2', 'y2']]) {
    if (command[x] === undefined) continue;
    moved[x] = (command[x] + dx) / em;
    moved[y] = (command[y] + dy) / em;
  }
  return moved;
}

function outline(char) {
  // charToGlyph answers .notdef (index 0) for a character the font does not hold.
  if (font.charToGlyphIndex(char) === 0) fail(`the font has no glyph for ${char}`);
  // Drawn at one em per `em` units, so the commands stay in font units (y down)
  // and are scaled here: opentype.js can emit NaN coordinates when it scales
  // and offsets a glyph itself.
  const path = font.charToGlyph(char).getPath(0, 0, em);
  if (path.commands.length === 0) fail(`the glyph for ${char} is empty`);
  const box = path.getBoundingBox();
  const dx = em * 0.5 - (box.x1 + box.x2) / 2;
  const dy = em * 0.5 - (box.y1 + box.y2) / 2;
  const centred = new opentype.Path();
  centred.commands = path.commands.map((command) => place(command, dx, dy));
  const d = centred.toPathData(4);
  if (/NaN|Infinity/.test(d)) fail(`the outline for ${char} holds a bad coordinate`);
  return d;
}

const quote = (text) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const glyphs = CHARS.map((char) => `  ${quote(char)}: ${quote(outline(char))}`).join(',\n');

await writeFile(
  out,
  `// Generated by tools/glyphs.mjs from ${record('fullName')}. Do not edit: run
// \`node tools/glyphs.mjs <font.ttf>\` to write it again.

/** The font's own copyright and licence lines, for the credit the site prints. */
export const GLYPH_CREDIT: string = ${quote(credit)};

/**
 * The four direction characters as SVG path data in a 1 x 1 em box, y down,
 * each outline's bounding box centred on (0.5, 0.5).
 */
export const GLYPHS: Readonly<Record<'北' | '東' | '南' | '西', string>> = {
${glyphs}
};
`,
  'utf8'
);
console.log(`[glyphs] wrote ${out}`);
